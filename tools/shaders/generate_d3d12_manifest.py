"""Generates src/graphics/gr2port_d3d12/shaders_manifest.cmake.

Every HLSL file under src/graphics/gr2port_d3d12/shaders is compiled by dxc at
build time. Listing them by hand in gr2port_d3d12.cmake would mean that a shader
dropped into the tree but forgotten in the list is never compiled -- it would look
ported, count as ported in the coverage report, and fail only on a console.

So the list is generated from the directory instead:

  python3 tools/shaders/generate_d3d12_manifest.py           # rewrite the file
  python3 tools/shaders/generate_d3d12_manifest.py --check   # exit 1 if stale

The file is checked in, and source-guard runs --check, so a stale manifest fails
in seconds instead of hiding a shader from the build.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SHADER_DIR = ROOT / "src/graphics/gr2port_d3d12/shaders"
MANIFEST = ROOT / "src/graphics/gr2port_d3d12/shaders_manifest.cmake"

# Extension -> dxc stage, matching gr2_hlsl_stage() in cmake/GR2D3D12Shaders.cmake.
STAGES = {
    ".vert": "vs",
    ".frag": "ps",
    ".pix": "ps",
    ".comp": "cs",
    ".geom": "gs",
    ".hull": "hs",
    ".tesc": "hs",
    ".dom": "ds",
    ".tese": "ds",
    ".ms": "ms",
    ".as": "as",
}

HEADER = """\
# SPDX-FileCopyrightText: Copyright 2026 GR2toXBOX contributors
# SPDX-License-Identifier: GPL-2.0-or-later
#
# GENERATED by tools/shaders/generate_d3d12_manifest.py -- do not edit.
#
# Every HLSL shader in this directory, compiled by dxc to DXIL at build time.
# Regenerate after adding or removing a shader:
#
#   python3 tools/shaders/generate_d3d12_manifest.py
#
# `generate_d3d12_manifest.py --check` runs in source-guard, so a shader added
# without regenerating this file fails the cheap job rather than being silently
# left out of the build.

"""


def stage_of(path: Path) -> str:
    # world.vert.hlsl -> ".vert"
    stem = path.name
    if not stem.endswith(".hlsl"):
        raise SystemExit(f"{path}: not an .hlsl file")
    staged = Path(stem[: -len(".hlsl")])
    ext = staged.suffix.lower()
    if ext not in STAGES:
        raise SystemExit(
            f"{path}: no stage in the name. Name the file after the GLSL stage it "
            f"replaces, with an .hlsl suffix (world.vert.hlsl). Known: "
            f"{', '.join(sorted(STAGES))}"
        )
    return ext


def symbol_of(relative: Path) -> str:
    # common/world.vert.hlsl -> common_world_vert
    parts = list(relative.parent.parts) if str(relative.parent) != "." else []
    name = relative.name[: -len(".hlsl")].replace(".", "_")
    parts.append(name)
    return "_".join(parts)


def render() -> str:
    lines = [HEADER]
    files = sorted(p for p in SHADER_DIR.rglob("*.hlsl"))
    for path in files:
        relative = path.relative_to(SHADER_DIR)
        stage_of(relative)
        lines.append(
            f"gr2port_add_hlsl_shader({relative.as_posix()} {symbol_of(relative)})\n"
        )
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the manifest is stale")
    args = parser.parse_args()

    wanted = render()
    if args.check:
        current = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
        if current != wanted:
            print(f"{MANIFEST.relative_to(ROOT)} is stale.", file=sys.stderr)
            print("  Run: python3 tools/shaders/generate_d3d12_manifest.py", file=sys.stderr)
            return 1
        count = wanted.count("gr2port_add_hlsl_shader(")
        print(f"d3d12 manifest: up to date ({count} shaders)")
        return 0

    MANIFEST.write_text(wanted, encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(ROOT)} ({wanted.count('gr2port_add_hlsl_shader(')} shaders)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
